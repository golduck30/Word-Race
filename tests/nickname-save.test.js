const assert=require('node:assert/strict');
const E=require('../addons/spark-economy.js');
const cat={categories:Object.fromEntries(['skin','bottom','outfit','eyes','hair','glasses','beard'].map(t=>[t,[{id:'free',price:0},{id:'premium',price:30}]])),petBases:[{id:'🐶',price:0},{id:'🐱',price:40}],petWings:[{id:'wing:none',price:0},{id:'wing:angel',price:50}]};
const s={users:{},rooms:{}};
assert.equal(E.mutateWallet(s,'device-A',cat).coins,200);
E.bindNickname(s,'device-A','빠글이',cat);
E.mutateBuy(s,'device-A',cat,'hair','premium');
E.mutatePetBuy(s,'device-A',cat,'base','🐱');
E.mutatePetBuy(s,'device-A',cat,'wing','wing:angel');
const after=E.mutateWallet(s,'device-A',cat);
assert.equal(after.coins,80);
E.mutateWallet(s,'device-B',cat);
const b=E.bindNickname(s,'device-B','빠글이',cat);
assert.equal(b.coins,80,'same nickname across devices shares the same wallet');
assert.equal(b.owned.hair.premium,true);
assert.equal(b.petOwned.bases['🐱'],true);
assert.equal(b.petOwned.wings['wing:angel'],true);
E.mutateEquip(s,'device-B',cat,'hair','premium');
assert.equal(E.mutateWallet(s,'device-A',cat).look.hair,'premium');
E.mutatePetEquip(s,'device-B',cat,'base','🐱');
assert.equal(E.mutateWallet(s,'device-A',cat).petLook.base,'🐱');
assert.equal(E.bindNickname(s,'device-B','빠글이',cat).coins,80,'repeat bind does not reset coins');
assert.notEqual(E.bindNickname(s,'device-C','다른친구',cat).coins,80);
console.log('nickname saving across devices: PASS');
