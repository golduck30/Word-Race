'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const E=require('../addons/spark-economy.js');
const catalog=JSON.parse(fs.readFileSync(path.join(__dirname,'../assets/nonemo/catalog.json'),'utf8'));
const state={users:{},rooms:{}};
const a=E.mutateWallet(state,'a',catalog),b=E.mutateWallet(state,'b',catalog);
assert.equal(a.coins,200);assert.equal(b.coins,200);
const cat='outfit',buyable=catalog.categories[cat].find(x=>x.price>0);
assert.ok(buyable,'need a priced asset');
// Shop prices were increased fivefold; a 200-coin starter wallet cannot buy most items.
const fundedCoins=Math.max(200,buyable.price+150);state.users.a.coins=fundedCoins;
const bought=E.mutateBuy(state,'a',catalog,cat,buyable.id);
assert.equal(bought.coins,fundedCoins-buyable.price);
const again=E.mutateBuy(state,'a',catalog,cat,buyable.id);
assert.equal(again.coins,bought.coins,'no double purchase charge');
assert.equal(E.mutateEquip(state,'a',catalog,cat,buyable.id).look.outfit,buyable.id);
E.mutateWallet(state,'c',catalog);
E.mutateBet(state,'a',catalog,'111111',1,'p1',1000);
E.mutateBet(state,'b',catalog,'111111',1,'p2',1000);
E.mutateBet(state,'c',catalog,'111111',1,'p2',1000);
assert.throws(()=>E.mutateBet(state,'a',catalog,'111111',1,'p1',1000),/이미 참여/);
let p1={completed:true,guesses:['ㅁㅁㅁㅁㅁ','ㄱㄴㄷㄹㅁ'],solvedTimestamp:1400};
let p2={completed:true,guesses:['ㅁㅁㅁㅁㅁ'],solvedTimestamp:0};
const room={round:1,secretWord:'ㄱㄴㄷㄹㅁ',masterUid:'host',startedAt:1000,timeLimit:0,players:{host:{completed:true},p1,p2}};
assert.equal(E.readyToSettle(room,1),true);
const beforeA=state.users.a.coins,beforeB=state.users.b.coins;
const result=E.mutateSettle(state,catalog,'111111',1,room,2000);
assert.deepEqual(result.winners,['p1']);assert.equal(result.correct,1);assert.equal(result.pot,60);
assert.equal(state.users.a.coins,beforeA+60);assert.equal(state.users.b.coins,beforeB);
const againSettle=E.mutateSettle(state,catalog,'111111',1,room,2001);
assert.equal(againSettle.already,true);assert.equal(state.users.a.coins,beforeA+60);
const cloned=JSON.parse(JSON.stringify(room));cloned.players.p2.completed=false;
assert.equal(E.readyToSettle(cloned,1),false);
const room2=JSON.parse(JSON.stringify(room));room2.players.p1.guesses=[];
E.mutateBet(state,'b',catalog,'111111',2,'p2',2000);
const refund=E.mutateSettle(state,catalog,'111111',2,room2,3000);
assert.equal(refund.winners.length,0);assert.equal(refund.pot,20);
assert.equal(state.users.b.coins,beforeB,'no winner => refund');
const activeRoom={...room,players:{host:{completed:true},p1:{...p1,spectator:false},p2:{...p2,spectator:false},a:{spectator:true},b:{spectator:true}}};
assert.doesNotThrow(()=>E.validateBet(activeRoom,'a','p1',1,59000));
assert.throws(()=>E.validateBet(activeRoom,'a','p1',1,62000),/60초/);
assert.throws(()=>E.validateBet(activeRoom,'a','host',1,10000),/출제자/);
console.log('OK Spark economy: default, buy/equip, single bet, odds, refunds, duplicate settlement, deadline');
